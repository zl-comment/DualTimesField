"""Generate the preregistered complete 3-region x 3-seed experiment matrix."""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import subprocess
from pathlib import Path

import pandas as pd
import yaml

REGIONS = ("NSW1", "QLD1", "TAS1")
SEEDS = (2026, 2027, 2028)
ROOT = Path(__file__).resolve().parents[1]
TAG = "exploration_20261011"
OUTPUT = f"outputs/forecasting/{TAG}"
LOG = f"logs/forecasting/{TAG}"


def update(config, changes):
    result = copy.deepcopy(config)
    for dotted, value in changes.items():
        keys = dotted.split(".")
        block = result
        for key in keys[:-1]:
            block = block.setdefault(key, {})
        block[keys[-1]] = value
    return result


def variants():
    original = yaml.safe_load((ROOT / "configs/aemo_forecast_ic_calibrator.yaml").read_text())
    original = update(original, {"training.device_batches": True, "training.torch_threads": 2,
        "training.checkpoint_metrics": ["crps"], "training.primary_selection": "crps"})
    full = update(original, {"model.scarcity_router": "learned", "model.router_hidden_dim": 16,
        "model.event_forecast": True, "loss.tail_weight": 0.5,
        "loss.negative_tail_weight": 2.0, "loss.spike_tail_weight": 2.0})
    configurations = {"full": full}
    definitions = {
        "no_tail": {"loss.tail_weight": 0.0},
        "concat": {"model.scarcity_router": "concat"},
        "uniform": {"model.scarcity_router": "uniform"},
        "no_quantile_gate": {"model.quantile_gate": False},
        "no_event": {"model.event_forecast": False},
        "raw_history": {"model.head_input": "raw_history"},
        "no_fields": {"model.field_forecast": False},
        "no_ic": {"interconnector_exogenous.zero_values": True},
        "no_pd": {"predispatch_exogenous.zero_values": True},
        "no_scarcity": {f"{b}.zero_values": True for b in ("future_exogenous", "ctf_exogenous", "quantile_exogenous")},
        "gabor": {"model.dgf_type": "gabor"},
        "adaptive": {"model.dgf_type": "adaptive"},
        "echo": {"model.event_echo": True},
    }
    for name, changes in definitions.items():
        configurations[name] = update(full, changes)
    # A-D are a reconstruction of the original cumulative input ladder, not
    # claims of monotonic improvements or the sole causal ablations.
    ladder = update(original, {"model.quantile_gate": False})
    configurations["D_all_inputs"] = ladder
    configurations["C_predispatch"] = update(ladder, {"interconnector_exogenous.zero_values": True})
    configurations["B_scarcity"] = update(configurations["C_predispatch"], {"predispatch_exogenous.zero_values": True})
    configurations["A_history"] = update(configurations["B_scarcity"], {
        f"{b}.zero_values": True for b in ("future_exogenous", "ctf_exogenous", "quantile_exogenous")})
    configurations["concat_no_tail"] = original
    configurations["pd_calibrator"] = update(original, {"interconnector_exogenous.zero_values": True})
    configurations["pd_nofields"] = update(configurations["pd_calibrator"], {"model.field_forecast": False})
    for state in ("dgf", "raw", "none"):
        configurations[f"event_joint_{state}"] = update(full, {"model.event_field": True,
            "model.event_state_source": state, "model.event_recent_extremes": True,
            "loss.event_nll_weight": 0.2, "loss.event_anchor_weight": 0.1})
        configurations[f"event_frozen_{state}"] = update(configurations[f"event_joint_{state}"], {
            "event_training.trunk_output_directory": f"{OUTPUT}/checkpoints/static/full",
            "event_training.epochs": 40, "event_training.learning_rate": 0.001})
    configurations["event_joint_raw_no_extremes"] = update(configurations["event_joint_raw"], {"model.event_recent_extremes": False})
    return configurations


def quarter_config(config, quarter):
    edges = pd.date_range("2023-01-01", "2025-01-01", freq="QS")
    start, end = edges[quarter:quarter + 2]
    validation = start - pd.DateOffset(months=3)
    boundaries = {
        "train": {"start": "2015-01-01 00:00:00", "end_exclusive": str(validation)},
        "validation": {"start": str(validation), "end_exclusive": str(start)},
        "test": {"start": str(start), "end_exclusive": str(min(end + pd.Timedelta(hours=23), edges[-1]))},
    }
    return update(config, {"data.relabel_splits": True, "data.split_boundaries": boundaries})


def make_manifest():
    configs = variants()
    jobs, paths = [], []
    def add(name, config, protocol, kind="dual", baseline_kind=None, dependencies=None):
        path = f"configs/aemo_forecast_{TAG}_{protocol.replace('/', '_')}_{name}.yaml"
        config = update(config, {"training.output_directory": f"{OUTPUT}/checkpoints/{protocol}/{name}"})
        (ROOT / path).write_text("# Frozen exploration matrix; generated by forecasting.exploration_configs.\n" + yaml.safe_dump(config, sort_keys=False))
        paths.append(path)
        for seed in SEEDS:
            for region in REGIONS:
                job = {"id": f"{protocol}/{name}/{seed}/{region}", "kind": kind, "config": path,
                       "region": region, "seed": seed, "protocol": protocol, "variant": name,
                       "output": f"{OUTPUT}/runs/{protocol}/{name}/seed{seed}/{region}",
                       "dependencies": [f"{protocol}/{dependency}/{seed}/{region}" for dependency in (dependencies or [])]}
                if baseline_kind:
                    job["baseline_kind"] = baseline_kind
                jobs.append(job)
    # Prioritize the six scientific anchors before the remaining controls.
    ordered = ["full", "no_tail", "concat", "concat_no_tail", "no_ic", "no_fields"]
    ordered += [name for name in configs if name not in ordered]
    for name in ordered:
        frozen = name.startswith("event_frozen")
        add(name, configs[name], "static", "frozen_event" if frozen else "dual",
            dependencies=["full"] if frozen else [])
    for kind in ("xgboost", "linear", "dlinear", "patchtst", "gatets", "gatets_adapter", "event_controls"):
        add(kind, configs["full"], "static", "baseline", kind)
    # Rolling is a separate matched protocol. All quarters and seeds run,
    # regardless of the static test ranking. No winner-driven test tuning.
    for q in range(8):
        for name in ("full", "no_tail", "concat", "no_ic", "no_fields", "pd_calibrator", "pd_nofields"):
            add(name, quarter_config(configs[name], q), f"rolling/q{q}")
        for kind in ("xgboost", "dlinear", "patchtst", "gatets_adapter"):
            add(kind, quarter_config(configs["full"], q), f"rolling/q{q}", "baseline", kind)
    # A different target treatment is reported separately, never pooled raw.
    for name in ("full", "no_tail", "concat"):
        add(name, update(configs[name], {"data.price_cap": 650.0}), "capped650")
    add("xgboost", update(configs["full"], {"data.price_cap": 650.0}), "capped650", "baseline", "xgboost")
    hashes = {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in paths}
    data_paths = set()
    for config in configs.values():
        data_paths.update(config["data"]["region_files"].values())
        for block in ("future_exogenous", "ctf_exogenous", "quantile_exogenous", "predispatch_exogenous", "interconnector_exogenous"):
            data_paths.update(config[block]["region_files"].values())
        data_paths.add(config["origin_context"]["path"])
    data_hashes = {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in sorted(data_paths)}
    manifest = {"name": TAG, "regions": REGIONS, "seeds": SEEDS, "source_commit": subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(), "config_hashes": hashes,
        "data_hashes": data_hashes, "selection": "unweighted validation raw-price CRPS approximation",
        "test_role": "retrospective exploration; neither 2023-24 nor 2025 is an unseen holdout",
        "jobs": jobs}
    directory = ROOT / LOG
    directory.mkdir(parents=True, exist_ok=True)
    manifest_path = directory / "manifest.json"
    if (directory / "manifest.status.json").exists():
        raise RuntimeError("A run status exists; refusing to replace its frozen manifest")
    manifest_path.write_text(json.dumps(manifest, indent=2))
    print(f"{manifest_path}: {len(jobs)} jobs, {len(paths)} configs, every cell has 3 regions x 3 seeds")
    return manifest


if __name__ == "__main__":
    argparse.ArgumentParser(description=__doc__).parse_args()
    make_manifest()
